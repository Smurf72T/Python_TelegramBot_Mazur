#!/bin/bash

# =============================================================================
# Entrypoint скрипт для Django Admin Panel
# =============================================================================
# Этот скрипт выполняется при запуске контейнера Django и выполняет
# следующие подготовительные действия перед запуском приложения:
# 1. Определение хоста базы данных в зависимости от окружения
# 2. Ожидание готовности базы данных PostgreSQL
# 3. Применение миграций Django
# 4. Создание суперпользователя (если не существует)
# 5. Запуск Django-сервера
# =============================================================================

# =============================================================================
# Определение окружения выполнения
# =============================================================================
# RUN_ENV: переменная окружения, определяющая где запущено приложение
# - "docker": приложение работает внутри Docker Compose
# - "local": приложение работает локально без Docker
# Значение по умолчанию: "local" (если переменная не задана)
RUN_ENV=${RUN_ENV:-"local"}

# =============================================================================
# Определение хоста базы данных
# =============================================================================
# Хост базы данных зависит от окружения выполнения:
# - В Docker: используем имя сервиса "db" (из docker-compose.yml)
# - Локально: используем "localhost"
if [ "$RUN_ENV" = "docker" ]; then
    # В Docker-сети контейнеры обращаются друг к другу по именам сервисов
    DB_HOST=${DB_HOST_DOCKER:-"db"}
else
    # При локальном запуске БД доступна на localhost
    DB_HOST=${DB_HOST_LOCAL:-"localhost"}
fi

# =============================================================================
# Конфигурация подключения к базе данных
# =============================================================================
# Параметры подключения к PostgreSQL с значениями по умолчанию
# Если переменная не задана в .env, используется значение по умолчанию
DB_PORT=${DB_PORT:-5432}              # Порт PostgreSQL
DB_USER=${DB_USER:-postgres}         # Имя пользователя
DB_PASSWORD=${DB_PASSWORD:-postgres} # Пароль пользователя

# =============================================================================
# Ожидание готовности базы данных
# =============================================================================
# PostgreSQL может не быть сразу готова к подключениям при старте контейнера.
# Используем цикл ожидания с проверкой готовности через pg_isready.
echo "Ожидание готовности базы данных на хосте $DB_HOST..."
max_retries=60     # Максимальное количество попыток подключения
retry_delay=2      # Задержка между попытками (в секундах)
attempt=1          # Счетчик текущей попытки

# Цикл ожидания готовности базы данных
# pg_isready: утилита PostgreSQL, проверяющая готовность сервера к подключениям
while ! pg_isready -h $DB_HOST -p $DB_PORT -U $DB_USER; do
  # Проверяем, превышен ли лимит попыток
  if [ $attempt -ge $max_retries ]; then
    echo "Ошибка: База данных не готова после $max_retries попыток"
    exit 1  # Завершаем работу с ошибкой
  fi
  # Выводим информацию о текущей попытке
  echo "Попытка $attempt/$max_retries: База данных не готова, ждем $retry_delay сек..."
  sleep $retry_delay  # Ждем перед следующей попыткой
  attempt=$((attempt + 1))  # Увеличиваем счетчик попыток
done

echo "База данных готова к подключению"

# =============================================================================
# Применение миграций Django
# =============================================================================
# Миграции Django применяют изменения схемы базы данных.
# --noinput: не запрашивать подтверждение при применении миграций
echo "Применение миграций..."
python /app/manage.py migrate --noinput

# =============================================================================
# Создание суперпользователя Django
# =============================================================================
# Проверяем существование суперпользователя и создаем его при необходимости.
# Это позволяет автоматически настроить доступ к админке при первом запуске.
# Используем heredoc (<< EOF) для передачи Python-кода в интерактивную консоль Django.
echo "Создание суперпользователя..."
cat << EOF | python /app/manage.py shell
from django.contrib.auth import get_user_model
User = get_user_model()
# Проверяем, существует ли пользователь с именем admin_sup
if not User.objects.filter(username='admin_sup').exists():
    # Создаем суперпользователя с заданными учетными данными
    User.objects.create_superuser(
        'admin_sup',      # Имя пользователя
        'admin@admin.admin',  # Email
        'admin123'        # Пароль
    )
    print('Суперпользователь admin_sup успешно создан.')
else:
    print('Суперпользователь admin_sup уже существует.')
EOF

# =============================================================================
# Запуск Django-сервера
# =============================================================================
# exec: замещает текущий процесс sh командой python (важно для корректной
# передачи сигналов SIGTERM/SIGINT при остановке контейнера)
# 0.0.0.0:8000: сервер слушает на всех сетевых интерфейсах, порт 8000
echo "Запуск Django-сервера..."
exec python /app/manage.py runserver 0.0.0.0:8000
