"""
Модуль serializers.py

Этот модуль содержит сериализаторы Django REST Framework для моделей приложения events.
Сериализаторы обеспечивают преобразование сложных типов данных (например, моделей Django)
в JSON и обратно, что необходимо для работы с REST API.

Назначение модуля:
- Определение правил сериализации для каждой модели
- Валидация данных при создании и обновлении объектов
- Управление набором полей, доступных через API

Функциональные блоки:
1. Импорты и зависимости
2. UserProfileSerializer - сериализация профиля пользователя
3. EventSerializer - сериализация событий
4. BotStatisticsSerializer - сериализация статистики бота
5. UserStatisticsSerializer - сериализация статистики пользователя
6. AppointmentSerializer - сериализация встреч/назначений
"""

from rest_framework import serializers
from events.models import UserProfile, Event, BotStatistics, UserStatistics, Appointment


# ==============================================================================
# БЛОК 1: Сериализаторы профилей пользователей
# ==============================================================================

class UserProfileSerializer(serializers.ModelSerializer):
    """
    Сериализатор для модели UserProfile.
    
    Отвечает за преобразование данных профиля пользователя в формат JSON и наоборот.
    Используется в API для получения и обновления информации о пользователях бота.
    
    Поля:
        telegram_id: Уникальный идентификатор пользователя в Telegram
        username: Имя пользователя в Telegram (без @)
        first_name: Имя пользователя
        last_name: Фамилия пользователя
        registered_at: Дата и время регистрации пользователя в системе
        export_token: Токен для экспорта данных пользователя
    
    Примечания:
        - Все поля доступны только для чтения при получении через API
        - Поля пользователя обычно обновляются ботом, а не через API админки
    """
    
    class Meta:
        model = UserProfile
        fields = [
            'telegram_id', 
            'username', 
            'first_name', 
            'last_name', 
            'registered_at', 
            'export_token'
        ]


# ==============================================================================
# БЛОК 2: Сериализаторы событий
# ==============================================================================

class EventSerializer(serializers.ModelSerializer):
    """
    Сериализатор для модели Event.
    
    Обеспечивает сериализацию событий, созданных пользователями в календаре.
    Основной сериализатор для работы с событиями через REST API.
    
    Поля:
        id: Уникальный идентификатор события (автоматически генерируется)
        user_id: Идентификатор пользователя-владельца события
        name: Название/заголовок события
        event_date: Дата проведения события
        event_time: Время проведения события
        details: Подробное описание события
        is_public: Флаг публичности события (доступно ли другим пользователям)
    
    Использование:
        - Создание новых событий
        - Получение списка событий пользователя
        - Редактирование существующих событий
        - Отображение событий в календаре
    """
    
    class Meta:
        model = Event
        fields = [
            'id', 
            'user_id', 
            'name', 
            'event_date', 
            'event_time', 
            'details', 
            'is_public'
        ]


# ==============================================================================
# БЛОК 3: Сериализаторы статистики
# ==============================================================================

class BotStatisticsSerializer(serializers.ModelSerializer):
    """
    Сериализатор для модели BotStatistics.
    
    Предназначен для работы с общей статистикой работы бота.
    Содержит агрегированные данные о деятельности всех пользователей.
    
    Поля:
        date: Дата, за которую собрана статистика
        user_count: Общее количество зарегистрированных пользователей на эту дату
        event_count: Общее количество событий в системе на эту дату
        edited_events: Количество отредактированных событий за день
        cancelled_events: Количество отмененных событий за день
    
    Назначение:
        - Аналитика использования бота
        - Отслеживание активности пользователей
        - Генерация отчетов для администраторов
    """
    
    class Meta:
        model = BotStatistics
        fields = [
            'date', 
            'user_count', 
            'event_count', 
            'edited_events', 
            'cancelled_events'
        ]


class UserStatisticsSerializer(serializers.ModelSerializer):
    """
    Сериализатор для модели UserStatistics.
    
    Отвечает за сериализацию персональной статистики каждого пользователя.
    Хранит метрики активности конкретного пользователя.
    
    Поля:
        user_telegram_id: Идентификатор пользователя Telegram
        created_events: Общее количество созданных пользователем событий
        edited_events: Общее количество отредактированных пользователем событий
        cancelled_events: Общее количество отмененных пользователем событий
        updated_at: Дата и время последнего обновления статистики
    
    Особенности:
        - Статистика обновляется автоматически при действиях пользователя
        - Используется для аналитики активности отдельных пользователей
        - Может применяться для выявления активных и неактивных пользователей
    """
    
    class Meta:
        model = UserStatistics
        fields = [
            'user_telegram_id', 
            'created_events', 
            'edited_events', 
            'cancelled_events', 
            'updated_at'
        ]


# ==============================================================================
# БЛОК 4: Сериализаторы встреч
# ==============================================================================

class AppointmentSerializer(serializers.ModelSerializer):
    """
    Сериализатор для модели Appointment.
    
    Обеспечивает работу с встречами, созданными на основе событий.
    Отличается от Event тем, что предназначен для совместного планирования
    встреч между пользователями.
    
    Поля:
        id: Уникальный идентификатор встречи
        organizer_id: Telegram ID организатора встречи (создавшего встречу)
        event: Ссылка на событие, на основе которого создана встреча
        participant_telegram_id: Telegram ID участника встречи (приглашенного пользователя)
        date: Дата проведения встречи
        time: Время проведения встречи
        details: Дополнительные детали встречи
        status: Статус встречи (например: 'pending', 'confirmed', 'cancelled', 'completed')
        created_at: Дата и время создания записи о встрече
    
    Возможные статусы:
        - pending: Встреча в ожидании подтверждения
        - confirmed: Встреча подтверждена участником
        - cancelled: Встреча отменена
        - completed: Встреча завершена
    
    Использование:
        - Создание приглашений на встречи
        - Управление статусом встреч
        - Получение списка встреч для пользователя (как организатора, так и участника)
    """
    
    class Meta:
        model = Appointment
        fields = [
            'id', 
            'organizer_id', 
            'event', 
            'participant_telegram_id', 
            'date', 
            'time', 
            'details', 
            'status', 
            'created_at'
        ]
