from typing import Optional
from notes_bot.database import DatabasePool
from notes_bot.event_crud import EventCRUD


class PublicEventsManager:
    """
    Менеджер управления публичными событиями для бота заметок.

    Этот класс предоставляет функционал для управления видимостью событий
    и получения списка публичных событий от других пользователей. Класс
    использует пул соединений с базой данных и CRUD-операции для работы
    с данными событий.

    Основные возможности:
        - Переключение видимости события (публичное/приватное)
        - Получение списка всех публичных событий от других пользователей
        - Проверка прав доступа к событиям

    Пример использования:
        ```python
        manager = PublicEventsManager(db_pool, event_crud)

        # Сделать событие публичным
        result = manager.toggle_public(user_id=123, event_id="evt_456")

        # Получить список публичных событий
        events_list = manager.get_public_events(current_user_id=123)
        ```

    Attributes:
        db_pool (DatabasePool): Пул соединений с базой данных для выполнения
            SQL-запросов. Обеспечивает эффективное управление подключениями.
        event_crud (EventCRUD): Объект для CRUD-операций над событиями.
            Используется для базовых операций чтения/записи событий.

    Note:
        Класс не хранит состояние между вызовами методов. Каждый метод
        самостоятельно получает соединение из пула и возвращает его после
        завершения работы.
    """

    def __init__(self, db_pool: DatabasePool, event_crud: EventCRUD) -> None:
        """
        Инициализация менеджера публичных событий.

        Создает экземпляр менеджера с необходимыми зависимостями для работы
        с базой данных и событиями. Все зависимости передаются извне для
        обеспечения тестируемости и гибкости кода.

        Args:
            db_pool (DatabasePool): Экземпляр пула соединений с базой данных.
                Должен быть предварительно инициализирован и готов к работе.
            event_crud (EventCRUD): Экземпляр объекта для CRUD-операций
                над событиями. Предоставляет базовый доступ к данным событий.

        Returns:
            None: Конструктор не возвращает значение.

        Example:
            ```python
            db_pool = DatabasePool(connection_string)
            event_crud = EventCRUD(db_pool)
            manager = PublicEventsManager(db_pool, event_crud)
            ```
        """
        self.db_pool = db_pool
        self.event_crud = event_crud

    def toggle_public(self, user_id: int, event_id: str) -> str:
        """
        Переключить видимость события (публичное/приватное).

        Метод изменяет флаг видимости указанного события. Если событие было
        публичным — станет приватным, и наоборот. Перед изменением выполняется
        проверка прав доступа: событие должно существовать и принадлежать
        указанному пользователю.

        Операция выполняется атомарно в рамках одной транзакции базы данных.
        В случае ошибки транзакция откатывается, соединение возвращается в пул.

        Args:
            user_id (int): Идентификатор пользователя, который запрашивает
                изменение видимости. Должен совпадать с владельцем события.
            event_id (str): Идентификатор события в базе данных. Должен
                существовать и принадлежать указанному пользователю.

        Returns:
            str: Сообщение о результате операции. Содержит информацию о новом
                статусе видимости события ("публичным" или "приватным").

        Raises:
            ValueError: В следующих случаях:
                - Событие с указанным идентификатором не существует
                - Событие не принадлежит указанному пользователю
                - Ошибка доступа к базе данных

            DatabaseError: При ошибке подключения к базе данных или выполнения
                SQL-запроса (зависит от реализации DatabasePool).

        Example:
            ```python
            # Успешное переключение
            result = manager.toggle_public(user_id=123, event_id="evt_456")
            print(result)  # "Событие успешно сделано публичным"

            # Ошибка: событие не принадлежит пользователю
            manager.toggle_public(user_id=999, event_id="evt_456")
            # ValueError: Event evt_456 not found or access denied
            ```

        Note:
            Метод использует один SQL-запрос с условием проверки прав доступа.
            Это обеспечивает атомарность операции и защищает от гонок данных.
        """
        # Получаем соединение из пула для выполнения запросов
        conn = self.db_pool.get_connection()
        try:
            cursor = conn.cursor()

            # Атомарное обновление с проверкой прав доступа в одном запросе
            # UPDATE возвращает новое значение is_public только если строка найдена
            # и принадлежит пользователю (условие WHERE user_id = %s)
            cursor.execute(
                """
                UPDATE events
                SET is_public = NOT is_public
                WHERE id = %s
                  AND user_id = %s RETURNING is_public
                """,
                (event_id, user_id)
            )

            # Получаем результат обновления
            result = cursor.fetchone()

            # Если результат пустой — событие не найдено или не принадлежит пользователю
            if result is None:
                raise ValueError(f"Событие {event_id} не найдено или доступ запрещён")

            # Извлекаем новый статус видимости из результата запроса
            new_status = result[0]

            # Фиксируем изменения в базе данных
            conn.commit()

            # Формируем сообщение о результате на русском языке
            status_text = "публичным" if new_status else "приватным"
            return f"Событие успешно сделано {status_text}"

        except Exception as error:
            # При любой ошибке откатываем транзакцию для сохранения целостности данных
            conn.rollback()
            # Пробрасываем ошибку дальше для обработки вызывающим кодом
            raise error
        finally:
            # Возвращаем соединение в пул независимо от результата операции
            # Это важно для предотвращения утечек соединений
            self.db_pool.put_connection(conn)

    def get_public_events(self, current_user_id: Optional[int] = None) -> str:
        """
        Получить список всех публичных событий от других пользователей.

        Метод возвращает отформатированный текстовый список всех событий,
        которые помечены как публичные. По умолчанию исключает события
        текущего пользователя из результата (если передан current_user_id).

        Для каждого события отображается:
            - Имя автора (или "Аноним", если имя не указано)
            - Название события
            - Дата и время проведения
            - Описание (если присутствует)

        Args:
            current_user_id (Optional[int]): Идентификатор текущего пользователя.
                Если передан, его события будут исключены из результата.
                Если None — будут показаны все публичные события без исключений.
                По умолчанию None.

        Returns:
            str: Отформатированное текстовое сообщение со списком публичных
                событий. Каждое событие на отдельной строке. Если событий нет —
                возвращается сообщение "Нет доступных публичных событий".

        Raises:
            DatabaseError: При ошибке подключения к базе данных или выполнения
                SQL-запроса (зависит от реализации DatabasePool).

        Example:
            ```python
            # Получить события для конкретного пользователя
            events = manager.get_public_events(current_user_id=123)
            print(events)
            # Доступные публичные события:
            # • Иван: Встреча (2024-01-15 14:00) - Обсуждение проекта

            # Получить все публичные события без исключений
            all_events = manager.get_public_events()
            ```

        Note:
            - Метод явно указывает необходимые колонки в SELECT-запросе,
              что делает код устойчивым к изменениям схемы базы данных.
            - Соединение с БД автоматически возвращается в пул после выполнения.
            - Транзакция откатывается при возникновении ошибок.

        Security:
            Метод не проверяет права доступа к событиям, так как возвращает
            только публичные данные. Однако рекомендуется передавать
            current_user_id для исключения личных событий пользователя из
            общего списка.
        """
        # Получаем соединение из пула для выполнения запросов
        conn = self.db_pool.get_connection()
        try:
            cursor = conn.cursor()

            # Формируем базовый SQL-запрос для получения публичных событий
            # Явно указываем колонки для независимости от порядка полей в таблице
            query = """
                    SELECT e.id, e.name, e.event_date, e.event_time, e.details, u.username
                    FROM events e
                             LEFT JOIN users u ON e.user_id = u.telegram_id
                    WHERE e.is_public = TRUE \
                    """
            params = []

            # Если передан ID текущего пользователя, исключаем его события из результата
            # Это нужно, чтобы пользователь не видел свои события в списке "чужих"
            if current_user_id is not None:
                query += " AND e.user_id != %s"
                params.append(current_user_id)

            # Выполняем запрос с параметрами для защиты от SQL-инъекций
            cursor.execute(query, params)

            # Получаем все результаты запроса
            events = cursor.fetchall()

            # Если публичных событий нет, возвращаем информативное сообщение
            if not events:
                return "Нет доступных публичных событий"

            # Начинаем формировать сообщение со списком событий
            message_parts = ["Доступные публичные события:\n"]

            # Обрабатываем каждое событие для форматирования вывода
            for event in events:
                # Распаковываем данные события по порядку колонок в SELECT-запросе:
                # id, name, event_date, event_time, details, username
                _, title, date, time, description, author_name = event

                # Определяем имя автора для отображения
                # Если имя не указано в базе — показываем "Аноним"
                author_display = author_name if author_name else "Аноним"

                # Формируем основную строку информации о событии
                event_info = f"• {author_display}: {title} ({date} {time})"

                # Добавляем описание события, если оно присутствует
                if description:
                    event_info += f" - {description}"

                # Добавляем отформатированную строку в список частей сообщения
                message_parts.append(event_info)

            # Объединяем все части сообщения в единый текст с переносами строк
            return "\n".join(message_parts)

        except Exception as error:
            # При любой ошибке откатываем транзакцию для сохранения целостности данных
            conn.rollback()
            # Пробрасываем ошибку дальше для обработки вызывающим кодом
            raise error
        finally:
            # Возвращаем соединение в пул независимо от результата операции
            # Это важно для предотвращения утечек соединений
            self.db_pool.put_connection(conn)